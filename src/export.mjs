import { username } from './constellation.mjs';
import { CONFIG_VERSION, normalizeConfig } from './config-schema.mjs';

export const projectUrl = 'https://github.com/mnichols08/constellation';
/** The moving major tag README workflows follow. Move it to each compatible release. */
export const ACTION_REF = 'v5';

export function installationLinks(repository, workflow, file = 'constellation.yml') {
  if (!/^[a-z\d][a-z\d-]{0,60}\.yml$/.test(file)) throw new Error('Use a simple .yml workflow filename.');
  const target = repository.trim();
  if (!/^[a-z\d][a-z\d-]*\/[a-z\d_.-]+$/i.test(target) || ['.', '..'].includes(target.split('/')[1])) throw new Error('Enter the workflow repository as owner/repository.');
  const [owner, repo] = target.split('/');
  const base = `https://github.com/${encodeURIComponent(owner)}/${encodeURIComponent(repo)}`;
  const install = new URL(`${base}/new/HEAD`);
  install.searchParams.set('filename', `.github/workflows/${file}`);
  install.searchParams.set('value', workflow);
  const create = new URL('https://github.com/new');
  create.searchParams.set('name', repo);
  create.searchParams.set('visibility', 'public');
  create.searchParams.set('readme', '1');
  return {
    // Large custom CSS can exceed browser/server URL limits. Keep copy/download available.
    install: install.href.length <= 8000 ? install.href : null,
    create: create.href,
    actions: `${base}/actions/workflows/${file}`,
  };
}

export function readmeSnippet(account, repository, filename = 'constellation.svg', label = 'GitHub constellation') {
  const name = account ? username(account) : 'My';
  const target = repository?.trim() || (account ? `${username(account)}/${username(account)}` : 'YOUR_USERNAME/YOUR_REPOSITORY');
  if (!/^[a-z\d][a-z\d-]*\/[a-z\d_.-]+$/i.test(target) && target !== 'YOUR_USERNAME/YOUR_REPOSITORY') throw new Error('Enter the workflow repository as owner/repository.');
  if (!/^[a-z\d][a-z\d._-]{0,120}\.svg$/i.test(filename)) throw new Error('Use a safe .svg filename for a GitHub README image.');
  const path = target.split('/').map(encodeURIComponent).join('/');
  const image = `https://raw.githubusercontent.com/${path}/output/${encodeURIComponent(filename)}`;
  return `[![${name} ${label}](${image})](${projectUrl})\n\nMade with [GitHub Constellation](${projectUrl}) by [@mnichols08](https://github.com/mnichols08).`;
}

export function renderWorkflow(_account, options, publishing = {}) {
  const { activityData, codingRhythmData, historyData, accountData, organizationData, ...configuration } = options;
  const normalized = normalizeConfig(configuration, { trustedCSS: true });
  // JSON escapes preserve literal CSS dollars while preventing GitHub Actions
  // from interpreting user-authored CSS as workflow expressions.
  const json = JSON.stringify({ ...normalized, version: CONFIG_VERSION }, null, 2).replace(/\$/g, '\\u0024');
  const config = json.split('\n').map(line => `            ${line}`).join('\n');
  const filename = publishing.filename || 'constellation.svg';
  if (!/^[a-z\d][a-z\d._-]{0,120}\.svg$/i.test(filename)) throw new Error('Use a safe .svg filename for an automatic GitHub README workflow.');
  const branch = publishing.branch || 'output';
  if (!/^[a-zA-Z0-9][a-zA-Z0-9._/-]{0,127}$/.test(branch) || branch.includes('..') || branch.endsWith('/') || branch.includes('//')) throw new Error('Enter a safe output branch name.');
  if (publishing.story && !['auto', 'projects', 'technical-shape', 'journey'].includes(publishing.story))
    throw new Error('Choose a supported publishing story.');
  if (publishing.story && ![480, 900].includes(publishing.targetWidth))
    throw new Error('Choose a 480px or 900px publishing width.');
  return `# Save as .github/workflows/constellation.yml
# Generated by GitHub Constellation. Settings and CSS match the preview.
name: Daily constellation
on:
  schedule:
    - cron: '17 6 * * *'
  workflow_dispatch:
permissions:
  contents: write
concurrency:
  group: constellation-output-\u0024{{ github.repository }}
  cancel-in-progress: false
jobs:
  generate:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v6
      - uses: mnichols08/constellation@${ACTION_REF}
        with:
          publish: 'true'
          output: '${filename}'
          output-branch: '${branch}'${publishing.story ? `\n          story: '${publishing.story}'\n          target-width: '${publishing.targetWidth}'` : ''}${publishing.sourceAccount || options.accountData?.type === 'Organization' || options.accountType === 'organization' || options.organizationUser ? `\n          username: '${username(_account)}'` : ''}
          config-json: |
${config}
`;
}

/**
 * A workflow that redraws an account's tech stack map every day and publishes
 * it beside any constellation image. It carries no design settings: the map
 * is drawn from what the account's public repositories declare.
 */
export function renderTechStackWorkflow(account, publishing = {}) {
  const login = username(account);
  const filename = publishing.filename || 'tech-stack.svg';
  if (!/^[a-z\d][a-z\d._-]{0,120}\.svg$/i.test(filename)) throw new Error('Use a safe .svg filename for an automatic GitHub README workflow.');
  const branch = publishing.branch || 'output';
  if (!/^[a-zA-Z0-9][a-zA-Z0-9._/-]{0,127}$/.test(branch) || branch.includes('..') || branch.endsWith('/') || branch.includes('//')) throw new Error('Enter a safe output branch name.');
  return `# Save as .github/workflows/tech-stack.yml
# Generated by GitHub Constellation.
name: Daily tech stack map
on:
  schedule:
    - cron: '47 6 * * *'
  workflow_dispatch:
permissions:
  contents: write
concurrency:
  group: constellation-output-\u0024{{ github.repository }}
  cancel-in-progress: false
jobs:
  generate:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v6
      - uses: mnichols08/constellation@${ACTION_REF}
        with:
          username: '${login}'
          tech-stack: 'true'
          publish: 'true'
          output: '${filename}'
          output-branch: '${branch}'
`;
}

/** True when text looks like a workflow that runs this Action. */
export const isWorkflow = (text) => typeof text === 'string' && /^\s*-?\s*uses:\s*['"]?mnichols08\/constellation@/m.test(text);

/**
 * The design inside a workflow file, as settings JSON text. Reads the literal
 * `config-json: |` block that "Add it to your GitHub profile" writes, from any
 * version of the Action. The result still goes through normal configuration
 * validation; nothing in the file is executed.
 */
export function workflowSettings(text) {
  if (typeof text !== 'string' || text.length > 400000) throw new Error('That workflow file is too big to read.');
  if (!isWorkflow(text)) throw new Error('That file doesn’t run the Constellation action.');
  const marker = /^([ \t]*)config-json:\s*\|[-+]?[ \t]*\r?$/m.exec(text);
  if (!marker) {
    if (/^[ \t]*config:\s*\S/m.test(text)) throw new Error('That workflow reads its design from a separate settings file. Open that .json file instead.');
    if (/^[ \t]*tech-stack:\s*['"]?true/m.test(text)) throw new Error('That workflow draws a tech stack map, which has no design settings to open.');
    throw new Error('That workflow has no saved design in it. It draws the default map.');
  }
  const lines = text.slice(marker.index + marker[0].length).replace(/^\r?\n/, '').split(/\r?\n/);
  const block = [];
  for (const line of lines) {
    // The block ends at the first line indented no deeper than its key.
    if (line.trim() && line.search(/\S/) <= marker[1].length) break;
    block.push(line);
  }
  const json = block.join('\n').trim();
  let settings;
  try { settings = JSON.parse(json); } catch { throw new Error('The design saved in that workflow isn’t valid JSON.'); }
  if (settings === null || typeof settings !== 'object' || Array.isArray(settings)) throw new Error('The design saved in that workflow isn’t a settings object.');
  return JSON.stringify(settings);
}

